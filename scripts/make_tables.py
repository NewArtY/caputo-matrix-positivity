def table_dirac():
    b4 = read('Table_Dirac_B4.csv')
    fits = read('Table_Dirac_B4_fits.csv')
    tail = read('Table_Dirac_tail.csv')

    def val(z, a, kc, col):
        if np.isinf(kc):
            r = one(b4[np.isclose(b4.zeta, z) & np.isclose(b4.alpha, a) & np.isinf(b4.kappa_c)])
        else:
            r = one(b4[np.isclose(b4.zeta, z) & np.isclose(b4.alpha, a) & np.isclose(b4.kappa_c, kc)])
        return r[col], r.get(col + '_err', np.nan)

    maxerr = 0.0

    def cell(z, a, kc, col, dec=4):
        nonlocal maxerr
        v, e = val(z, a, kc, col)
        if np.isfinite(e):
            maxerr = max(maxerr, float(e))
        return fixed(v, dec)

    def limit(z, a, q):
        nonlocal maxerr
        r = one(fits[np.isclose(fits.zeta, z) & np.isclose(fits.alpha, a) & (fits.quantity == q)])
        maxerr = max(maxerr, float(r.limit_err))
        return fixed(r.limit, 4)

    def slope(z, a):
        if a == 1.0:
            return '--', '--'
        x = tail[(tail.study == 'log_slope') & np.isclose(tail.zeta, z) & np.isclose(tail.alpha, a)
                 & (tail.quantity == 'dN_tot/dln(kappa_c) between 16 and 32')]
        r = one(x)
        return fixed(r.value, 4), fixed(r.analytic, 4)

    rows = []
    for z, zl in ((0.0, 'linear'), (1.0, 'circular')):
        for a in (1.0, 0.9, 0.8):
            s_num, s_an = slope(z, a)
            dn = limit(z, a, 'dN') if z == 1.0 else '0'
            al = '1' if a == 1.0 else f'{a}'
            rows.append(f'{zl if a == 1.0 else ""} & {al} & ' + ' & '.join(cell(z, a, kc, 'N_tot') for kc in (3.0, 8.0, 32.0))
                        + f' & {s_num} & {s_an} & {dn} & '
                        + ' & '.join(cell(z, a, kc, 'peak_Jx_band') for kc in (3.0, 32.0)) + ' & ' + limit(z, a, 'Jx_band') + r' \\')
        rows.append(r'\addlinespace[2pt]')
    rows = rows[:-1]
    head = [r' & & \multicolumn{3}{c}{$\mathcal N_{\mathrm{tot}}$ within $\kappa_c$} & \multicolumn{2}{c}{$\mathrm d\mathcal N_{\mathrm{tot}}/\mathrm d\ln\kappa_c$} & & \multicolumn{3}{c}{$\max_t|J_x|$ within $\kappa_c$} \\',
            r'\cmidrule(lr){3-5}\cmidrule(lr){6-7}\cmidrule(lr){9-11}',
            r'Polarization & $\alpha$ & $3$ & $8$ & $32$ & computed & Eq.~\eqref{eq:logdiv} & $\Delta\mathcal N_\infty$ & $3$ & $32$ & $\infty$ \\']
    cap = (r'Laser-driven Dirac model ($a_0=1$, $\tau_p=6$, $\delta=0.5$, $\gamma_\downarrow=0.02$, $\gamma_\phi=0.05$, '
           r'$\tau_c=1$, window $[-30,30]$): total excitation density at $t_f$ within the square $|\kappa_x|,|\kappa_y|\leq\kappa_c$, '
           r'its logarithmic slope between $\kappa_c=16$ and $32$ next to the prediction of Eq.~\eqref{eq:logdiv}, valley contrast '
           r'extrapolated to $\kappa_c\to\infty$, and peak of the band-referenced sheet current~\eqref{eq:current}, also extrapolated. '
           r'Densities in units of $(\omega_0/v_F)^2$, currents in units of $e\omega_0^2/v_F$. For $\alpha<1$ the values are Richardson '
           r'extrapolated in the number of time steps; the estimated discretization errors of the entries are below '
           + sci_up(maxerr) + r'.')
    body = table(cap, 'tab:dirac', 'llccccccccc', head, rows, tabcolsep='3.5pt')
    write('Table_08.tex', 'Table_Dirac_B4.csv, Table_Dirac_B4_fits.csv, Table_Dirac_tail.csv', body)


