def one(df):
    """Exactly one row is expected."""
    if len(df) != 1:
        raise RuntimeError(f'expected one row, found {len(df)}')
    return df.iloc[0]


def pdg_decimals(sd):
    """Number of decimals to keep for (mean, sd) by the PDG rule."""
    if not np.isfinite(sd) or sd <= 0:
        return None
    e = math.floor(math.log10(sd))
    lead = int(round(sd / 10 ** (e - 2)))          # three leading digits
    if lead >= 1000:                                # rounding spilled over (e.g. 0.09996)
        lead //= 10
        e += 1
    nsig = 2 if lead <= 354 else 1
    if lead >= 950:                                 # 0.95..0.999 -> 1.0
        e += 1
        nsig = 2
    return -(e - (nsig - 1))


def pm(mean, sd, scale=1.0):
    """'mean +/- sd' in math mode, PDG rounding."""
    mean *= scale
    sd *= scale
    dec = pdg_decimals(sd)
    if dec is None:
        return fixed(mean, 3)
    if dec < 0:                                     # sd >= 10: round to tens, hundreds, ...
        f = 10 ** (-dec)
        return rf'${int(round(mean / f) * f)}\pm{int(round(sd / f) * f)}$'
    return rf'${mean:.{dec}f}\pm{sd:.{dec}f}$'


def fixed(x, dec):
    s = f'{x:.{dec}f}'
    if float(s) == 0.0:
        s = s.replace('-', '')
    return s


def sig(x, n):
    """n significant digits in plain decimal notation."""
    if x == 0 or not np.isfinite(x):
        return '0' if x == 0 else '--'
    e = math.floor(math.log10(abs(x)))
    dec = max(n - 1 - e, 0)
    return f'{round(x, n - 1 - e):.{dec}f}'


def sci(x, n=2):
    r"""a x 10^b in math mode with n significant digits; 0 -> 0."""
    if x == 0:
        return '$0$'
    if not np.isfinite(x):
        return '--'
    e = math.floor(math.log10(abs(x)))
    m = x / 10 ** e
    ms = f'{m:.{n - 1}f}'
    if abs(float(ms)) >= 10:
        m /= 10
        e += 1
        ms = f'{m:.{n - 1}f}'
    return rf'${ms}\times10^{{{e}}}$'


def sci_up(x):
    r"""Upper bound a x 10^b with a one-digit mantissa that is rounded up."""
    e = math.floor(math.log10(abs(x)))
    m = math.ceil(abs(x) / 10 ** e - 1e-12)
    if m >= 10:
        m, e = 1, e + 1
    return rf'${m}\times10^{{{e}}}$'


def write(name, src, body):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), 'w', encoding='ascii', newline='\n') as f:
        f.write(HEADER.format(src=src))
        f.write(body.rstrip('\n') + '\n')
    print('wrote', name)


def table(caption, label, colspec, head, rows, size=r'\footnotesize', tabcolsep='4pt', pos='!tbp', note=None):
    out = [rf'\begin{{table}}[{pos}]', r'\centering', size, rf'\setlength{{\tabcolsep}}{{{tabcolsep}}}',
           rf'\caption{{{caption}}}', rf'\label{{{label}}}', r'\vspace{3pt}',
           r'\resizebox{\ifdim\width>\textwidth\textwidth\else\width\fi}{!}{%',
           rf'\begin{{tabular}}{{{colspec}}}', r'\toprule']
    out += head
    out.append(r'\midrule')
    out += rows
    out += [r'\bottomrule', r'\end{tabular}}']
    if note:
        out.append(note)
    # the space inserted below the caption is taken back here, so that the height of the float is unchanged
    out += [r'\par\vspace{-3pt}', r'\end{table}']
    return '\n'.join(out)


