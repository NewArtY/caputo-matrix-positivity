def pct_range(med, lo, hi):
    def f(x):
        x *= 100.0
        if x >= 1000:
            return r'{>}10^{3}'
        return sig(x, 2) if x < 10 else f'{x:.0f}'
    return rf'${f(med)}$ (${f(lo)}$--${f(hi)}$)'


