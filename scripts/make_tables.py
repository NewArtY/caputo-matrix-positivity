def table_factorial():
    d = read('Table_B2_factorial.csv')
    cols = [(a, s) for a in (0.3, 0.6) for s in ('mixed', 'nearly_pure', 'pure')]

    def entry(cell, a, s):
        x = d[(d.cell == cell) & np.isclose(d.alpha, a) & (d.state == s) & (d.stage.isin(['main', 'extras']))]
        if len(x) == 0:
            return '--'
        r = one(x)
        if int(r.n_ok) != 10:
            raise RuntimeError('unexpected number of seeds')
        return pm(r.rel_fro_mean, r.rel_fro_sd, 100.0)

    def stepper(N, a, s):
        r = one(d[(d.cell == f'l1_stepper/N{N}') & np.isclose(d.alpha, a) & (d.state == s)])
        return sig(100 * r.rel_fro_median, 2)

    def row(label1, label2, cell):
        return f'{label1} & {label2} & ' + ' & '.join(entry(cell, a, s) for a, s in cols) + r' \\'

    rows = []
    blocks = [
        ('Unconstrained', [('soft', 'unc/soft-tuned'), (f'hard, ${G1}$', 'unc/hard-exp'), (f'hard, ${GA}$', 'unc/hard-pow')]),
        ('Linear head', [('soft', 'lin/soft-tuned'), (f'hard, ${G1}$', 'lin/hard-exp'), (f'hard, ${GA}$', 'lin/hard-pow'),
                         (f'hard, ${GA}$, $(\\tau,\\tau^\\alpha)$', 'lin/hard-pow/singular')]),
        ('Factor', [('soft', 'factor/soft-tuned'), (f'hard, ${G1}$', 'factor/hard-exp'), (f'hard, ${GA}$', 'factor/hard-pow'),
                    (f'hard, ${GA}$, $(\\tau,\\tau^\\alpha)$', 'factor/hard-pow/singular')]),
        ('Additive', [(f'hard, ${G1}$', 'add/hard-exp'), (f'hard, ${GA}$', 'add/hard-pow'),
                      (f'hard, ${GA}$, $(\\tau,\\tau^\\alpha)$', 'add/hard-pow/singular')]),
        ('Block gate', [(f'hard, ${GA}$', 'gate2b/hard-pow')]),
    ]
    for name, lst in blocks:
        for i, (lab, cell) in enumerate(lst):
            rows.append(row(name if i == 0 else '', lab, cell))
        rows.append(r'\addlinespace[2pt]')
    rows.append(r'\midrule')
    for N in (32, 128):
        rows.append(rf'\multicolumn{{2}}{{l}}{{L1 time stepper, $N={N}$}} & ' + ' & '.join(stepper(N, a, s) for a, s in cols) + r' \\')
    head = [r' & & \multicolumn{3}{c}{$\alpha=0.3$} & \multicolumn{3}{c}{$\alpha=0.6$} \\',
            r'\cmidrule(lr){3-5}\cmidrule(lr){6-8}',
            r'Output map & Initial condition & mixed & nearly pure & pure & mixed & nearly pure & pure \\']
    cap = (r'Factorial study for the driven two-level system: relative error $e_F$ in percent, mean $\pm$ standard deviation '
           r'over 10 seeds, for three initial states. Soft initial condition: penalty with the weight selected on three pilot seeds; '
           rf'hard initial condition with the gate ${G1}(\tau)=1-\mathrm{{e}}^{{-\beta\tau}}$ or ${GA}(\tau)=1-\mathrm{{e}}^{{-\beta\tau^\alpha}}$; '
           r'$(\tau,\tau^\alpha)$: second network input $\tau^\alpha$. The block-gate map coincides with the factor map for '
           r'full-rank initial states. All networks use the collocation mesh of the L1 time stepper with $N=128$, whose error is '
           r'given in the same metric.')
    body = table(cap, 'tab:factorial', 'llcccccc', head, rows, size=r'\scriptsize', tabcolsep='3pt')
    write('Table_02.tex', 'Table_B2_factorial.csv', body)


